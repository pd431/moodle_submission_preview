/**
 * Adds the setting to activity backups.
 */
class backup_local_submissioncheck_plugin extends backup_local_plugin {
    /**
     * The setting of the activity being backed up.
     *
     * @return backup_plugin_element
     */
    protected function define_module_plugin_structure() {
        $plugin = $this->get_plugin_element();
        $wrapper = new backup_nested_element($this->get_recommended_name());
        $setting = new backup_nested_element('submissioncheck', ['id'], ['mode']);
        $plugin->add_child($wrapper);
        $wrapper->add_child($setting);
        $setting->set_source_table('local_submissioncheck_cfg', ['cmid' => backup::VAR_MODID]);
        return $plugin;
    }
}
